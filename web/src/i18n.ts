export function errText(d: Dict, code: string): string {
  switch (code) {
    case "paused":
      return d.paused;
    case "snipe":
      return d.snipe;
    case "snipe_cap":
      return d.snipeCap;
    case "insufficient_gnot":
      return d.insufficient;
    case "slippage":
      return d.slippageFail;
    case "pool_not_found":
      return d.poolMissing;
    case "quote_failed":
      return d.quoteFail;
    default:
      return code;
  }
}
